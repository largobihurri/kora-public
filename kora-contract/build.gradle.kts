// KoraBuild.VERSION is generated from the Gradle project version (set once in the root build), so the library
// version has a single source of truth and needs no reflection or resource lookup at runtime.
val generateKoraBuild by tasks.registering {
    val libraryVersion = project.version.toString()
    val outputDir = layout.buildDirectory.dir("generated/koraBuild/kotlin")
    inputs.property("version", libraryVersion)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().file("eus/bihurri/kora/contract/KoraBuild.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by :kora-contract:generateKoraBuild from the Gradle project version. Do not edit.
            |package eus.bihurri.kora.contract
            |
            |/** Facts about the Kora build that produced this library. */
            |public object KoraBuild {
            |    /**
            |     * Version of the Kora library, e.g. `1.2.0`. Diagnostic only: peers report it in
            |     * [NodeDescriptor.koraVersion] so a log shows which Kora each app was built with. Compatibility is decided
            |     * by capability versions, never by this value.
            |     */
            |    public const val VERSION: String = "$libraryVersion"
            |}
            |
            """.trimMargin(),
        )
    }
}

kotlin.sourceSets.named("main") {
    kotlin.srcDir(generateKoraBuild)
}
